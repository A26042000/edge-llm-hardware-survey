#!/usr/bin/env python3
"""
census_robustness.py -- tests whether the census-based conclusions survive (i) removing
classes of evidence and (ii) random disagreement in the author-assigned classification.

Outputs: tab_robust.tex (table), robust_numbers.tex (macros used in the text)
"""
import random, collections
import bibtools
from census_data import CENSUS

B = bibtools.load()
REG = ["fw", "1w", "mw"]
NEIGH = {"fw": ["1w"], "1w": ["fw", "mw"], "mw": ["1w"]}
# designs whose reported power range crosses a class boundary (section 4 of the report)
BOUNDARY = {"wang2025pdacc": "1w", "mun2026spectra": "1w", "li2026reasoning": "1w",
            "kim2026revolver": "mw", "yoo2026trioracle": "mw", "dong2026reram": "fw",
            "shan2025platinum": "1w", "cao2026pnm": "1w"}
PRE = {r[1] for r in CENSUS if bibtools.is_preprint(B[r[1]])}

def rows(r):
    return dict(name=r[0], key=r[1], reg=r[4], ph=r[5], comps=list(r[6]), impl=r[7], fl=r[8])
BASE = [rows(r) for r in CENSUS]
missing = set(BOUNDARY) - {d["key"] for d in BASE}
assert not missing, missing

def matrix(ds):
    c = collections.Counter(); n = collections.Counter()
    for d in ds:
        n[d["reg"]] += 1
        for k in d["comps"]:
            c[(k, d["reg"])] += 1
    return c, n

def claims(ds):
    c, n = matrix(ds)
    ng = ["SM", "NORM", "ROPE", "ACT"]
    return {
        "K1": all(sum(c[("GEMM", r)] for r in REG) > sum(c[(k, r)] for r in REG)
                  for k in ["ATT", "KV", "SM", "NORM", "ROPE", "ACT", "MOE"]),
        "K2": c[("ROPE", "1w")] + c[("ROPE", "mw")] < 0.1 * (n["1w"] + n["mw"]),
        "K3": c[("MOE", "mw")] <= 1,
        "K4": c[("KV", "mw")] >= 5,
        "K5": c[("SM", "mw")] == max(c[(k, "mw")] for k in ng),
    }, c, n

SCEN = [
    ("Full census", lambda d: True, None),
    ("Without preprints", lambda d: d["key"] not in PRE, None),
    ("Without simulation-only rows", lambda d: d["impl"] not in ("Sim", "NR"), None),
    ("Without encoder-workload rows", lambda d: "e" not in d["fl"], None),
    ("Without operator-level units", lambda d: d["ph"] != "op", None),
    ("Without inferred-regime rows", lambda d: "r" not in d["fl"], None),
    ("Boundary designs moved one class", lambda d: True, BOUNDARY),
    ("Measured, peer-reviewed only", lambda d: d["key"] not in PRE and d["impl"].split("/")[0] in ("Si", "SoC", "FPGA"), None),
]
res = []
for lab, keep, move in SCEN:
    ds = [dict(d, reg=move.get(d["key"], d["reg"])) if move else d for d in BASE if keep(d)]
    k, c, n = claims(ds)
    res.append((lab, len(ds), c, n, k))
# designs found by the logged PRISMA search and not in the census (abstract-level coding)
import importlib.util, os
_spec = importlib.util.spec_from_file_location("audit", os.path.join("prisma", "audit_designs.py"))
_aud = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_aud)
AUD = [dict(name=a[0], key=a[1], reg=a[4], ph="op" if "op." in a[3] else "P+D", comps=list(a[5]), impl="NR", fl=a[6])
       for a in _aud.AUDIT]
for lab, extra in (("Census + search-audit designs", AUD),):
    ds = BASE + extra
    k, c, n = claims(ds)
    res.insert(len(res) - 1, (lab, len(ds), c, n, k))

# Monte-Carlo disagreement: each regime moves to a neighbouring class with p, each
# component tag is dropped with q (a second coder who disagrees often)
random.seed(1)
P, Q, RUNS = 0.2, 0.1, 10000
hold = collections.Counter()
for _ in range(RUNS):
    ds = []
    for d in BASE:
        reg = random.choice(NEIGH[d["reg"]]) if random.random() < P else d["reg"]
        comps = [x for x in d["comps"] if random.random() >= Q] or d["comps"][:1]
        ds.append(dict(d, reg=reg, comps=comps))
    k, _, _ = claims(ds)
    for kk, v in k.items():
        hold[kk] += v
mc = {k: hold[k] / RUNS for k in ["K1", "K2", "K3", "K4", "K5"]}

CK = lambda b: "\\ding{51}" if b else "\\ding{55}"
L = ["% ---- AUTO-GENERATED by census_robustness.py ----",
     "\\begin{table*}[t]", "\\centering",
     "\\caption{Robustness of the census conclusions. Each row recomputes the gap matrix "
     "(\\cref{fig:gapheat}) on a subset or a reclassification of the census; the middle columns give "
     "the cells the text relies on (several-W/single-W/mW), and the last five columns state whether "
     "each conclusion still holds. K1: GEMM is the most-targeted component overall; K2: fewer than one in ten "
     "single-watt and milliwatt designs (pooled) target RoPE; K3: at most one milliwatt design targets MoE "
     "routing; K4: at least five milliwatt designs handle the KV cache; K5: Softmax is the "
     "most-covered non-GEMM operator at milliwatt scale. The last row gives the fraction of %d "
     "random reclassifications (each design moved to a neighbouring power class with probability %.1f "
     "and each component tag dropped with probability %.1f) in which the conclusion holds.}" % (RUNS, P, Q),
     "\\label{tab:robust}", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
     "\\begin{adjustbox}{max width=\\textwidth}", "\\begin{tabular}{@{}lrcccccccccc@{}}", "\\toprule",
     "Scenario & $n$ & designs per class & RoPE & MoE & KV\\$ & Softmax & K1 & K2 & K3 & K4 & K5\\\\",
     "\\midrule"]
fmt = lambda c, k: "/".join(str(c[(k, r)]) for r in REG)
for lab, nn, c, n, k in res:
    L.append(f"{lab} & {nn} & {'/'.join(str(n[r]) for r in REG)} & {fmt(c, 'ROPE')} & {fmt(c, 'MOE')} & "
             f"{fmt(c, 'KV')} & {fmt(c, 'SM')} & " + " & ".join(CK(k[x]) for x in ["K1", "K2", "K3", "K4", "K5"]) + "\\\\")
L += ["\\midrule",
      f"Random reclassification & {len(BASE)} & \\multicolumn{{5}}{{c}}{{fraction of runs in which the conclusion holds}} & "
      + " & ".join(f"{100 * mc[x]:.0f}\\%" for x in ["K1", "K2", "K3", "K4", "K5"]) + "\\\\",
      "\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{table*}"]
open("tab_robust.tex", "w", encoding="utf-8").write("\n".join(L) + "\n")

npre = len(PRE)
open("robust_numbers.tex", "w").write(
    "\\newcommand{\\ncensuspre}{%d}\n\\newcommand{\\ncensuspeer}{%d}\n\\newcommand{\\nstrict}{%d}\n"
    % (npre, len(BASE) - npre, res[-1][1]))
print("preprints in census:", npre, sorted(PRE))
for lab, nn, c, n, k in res:
    print(f"{lab:36s} n={nn:3d} classes={[n[r] for r in REG]} ROPE={fmt(c,'ROPE')} MOE={fmt(c,'MOE')} KV={fmt(c,'KV')} SM={fmt(c,'SM')}", k)
print("MC", mc)
