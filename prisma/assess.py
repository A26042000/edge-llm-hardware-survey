#!/usr/bin/env python3
"""
assess.py -- merges the title- and abstract-level decisions for candidates.csv, writes
assessed.csv (decision + reason per record) and audit_designs.py (abstract-level census rows of
the eligible designs), and the PRISMA numbers used by the paper (prisma_numbers.tex).
"""
import csv, json, os, re
from codes_title import TITLE
from codes_abstract import ABSTRACT, PRE2023, CODE

H = os.path.dirname(os.path.abspath(__file__))
REASON = {"V": "encoder, vision, speech or other non-LLM workload without a transferable component unit",
          "S": "software, benchmark, characterization, thesis or methodology (no hardware design)",
          "D": "not about LLM inference hardware",
          "C": "outside the edge resource regime",
          "U": "edge regime not established by the source",
          "T": "training or fine-tuning hardware",
          "R": "duplicate, extended version or artifact of an included design",
          "X": "security, reliability or thermal study",
          "Y": "eligible"}

old = {}
for line in open(os.path.join(H, "cand_list.txt"), encoding="utf-8"):
    m = re.match(r"(\d+) \d{4} .*? \| (.*)$", line.rstrip("\n"))
    if m: old[m.group(2)[:100]] = int(m.group(1))

rows = list(csv.DictReader(open(os.path.join(H, "candidates.csv"), encoding="utf-8")))
out, audit = [], []
for r in rows:
    t = r["title"]
    i = old.get(t[:140][:100])
    if i is None:
        key = next(k for k in PRE2023 if t.startswith(k) or k in t)
        code, stage, ck = PRE2023[key], "abstract", key if PRE2023[key] == "Y" else None
    else:
        code = TITLE[i]; stage = "title"
        if code == "?": code, stage = ABSTRACT[i], "abstract"
        ck = i if code == "Y" else None
    out.append(dict(r, decision=code, reason=REASON[code], stage=stage))
    if code == "Y":
        name, plat, reg, comps, fl = CODE[ck]
        audit.append((name, r["id"], int(r["year"]), plat, reg, comps, fl))

with open(os.path.join(H, "assessed.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(out[0].keys())); w.writeheader(); w.writerows(out)
with open(os.path.join(H, "audit_designs.py"), "w", encoding="utf-8") as f:
    f.write("# AUTO-GENERATED by assess.py: eligible designs found by the logged search and not in the census,\n"
            "# coded from title/abstract only.  (name, id, year, platform, regime, components, flags)\n")
    f.write("AUDIT = [\n" + "".join(f"    {a!r},\n" for a in audit) + "]\n")

c = json.load(open(os.path.join(H, "prisma_counts.json")))
from collections import Counter
dec = Counter(o["decision"] for o in out)
c["assessed"] = len(out); c["assessed_decisions"] = dict(dec); c["audit_eligible"] = dec["Y"]
c["assessed_title_level"] = sum(o["stage"] == "title" for o in out)
c["assessed_abstract_level"] = sum(o["stage"] == "abstract" for o in out)
json.dump(c, open(os.path.join(H, "prisma_counts.json"), "w"), indent=1)

import sys
sys.path.insert(0, os.path.join(H, ".."))
from census_data import CENSUS
ck = {r[1] for r in CENSUS}
recs = [json.loads(l) for l in open(os.path.join(H, "screened.jsonl"), encoding="utf-8")]
P = [r for r in recs if r["decision"] != "exclude"]
cen = [r for r in P if r["bibkey"] in ck]; cit = [r for r in P if r["bibkey"] and r["bibkey"] not in ck]
cen_designs = len({r["bibkey"] for r in cen})
ex = c["excluded_by_rule"]
M = {
 "pidOA": c["identified"]["openalex"], "pidAX": c["identified"]["arxiv"], "pidTot": c["identified_total"],
 "pdup": c["duplicates_removed"], "puniq": c["unique"], "pexcl": c["excluded_total"],
 "pexNoHW": ex.get("no hardware contribution (algorithm or software only)", 0),
 "pexWork": ex.get("not about Transformer/LLM inference workloads", 0),
 "pexEDA": ex.get("LLMs used for hardware design or EDA", 0),
 "pexOther": ex.get("hardware security / reliability only", 0) + ex.get("training hardware only", 0),
 "ppass": c["passed_screening"], "pcitedFound": c["cited_2020plus_found"], "pcitedTot": c["cited_2020plus"],
 "pcensusFound": c["census_found_by_search"], "pcensusOther": c["census"] - c["census_found_by_search"],
 "pcand": c["assessed"], "pcandTitle": c["assessed_title_level"], "pcandAbs": c["assessed_abstract_level"],
 "paudit": dec["Y"], "pcandEx": len(out) - dec["Y"],
 "pcenRec": len(cen), "pcenDB": cen_designs, "pcenOther": c["census"] - cen_designs,
 "pcitRec": len(cit), "pcitWorks": len({r["bibkey"] for r in cit}),
 "pscope": len(P) - len(cen) - len(cit) - len(out),
 "pcV": dec["V"], "pcS": dec["S"], "pcCU": dec["C"] + dec["U"], "pcOther": dec["D"] + dec["T"] + dec["R"] + dec["X"],
 "precallCensus": round(100 * c["census_found_by_search"] / c["census"]),
 "precallCited": round(100 * c["cited_2020plus_found"] / c["cited_2020plus"]),
}
with open(os.path.join(H, "..", "prisma_numbers.tex"), "w") as f:
    for k, v in M.items():
        f.write("\\newcommand{\\%s}{%s}\n" % (k, f"{v:,}".replace(",", "{,}") if isinstance(v, int) and v >= 1000 else v))
print(json.dumps(M, indent=1)); print(dict(dec))
